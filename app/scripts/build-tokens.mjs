// Token build. The files in ../tokens are the only source of truth:
//   colors.json      colour recipe (12-step ramps) + semantic colour roles
//   typography.json  type families, weights and the 80-style matrix
//   light.json       light effects
//   number.json      space, radius, size, stroke
//   motion.json      durations and easing
// and ../components/*.json, the component specs (token references + rules),
// and ../exports/shadcn/map.json, the shadcn/ui slot map.
// Writes (all generated, never edit by hand; a file is written only when its content changed):
//   src/styles/tokens.css            CSS custom properties
//   src/styles/typography.css        one class per type style (.type-body-md-regular ...)
//   src/tokens/tokens.resolved.json  everything resolved, for the docs site (server only)
//   src/tokens/components.json       the component specs alone, for code that runs in the browser
//   src/styles/components.css        per-size and per-type component variables (--btn-*)
//   ../docs/tokens-*.md              one reference page per source file
//   ../docs/components/*.md          one page per component spec
//   ../figma/tokens-studio.json      the whole system for Tokens Studio (Figma)
//   ../exports/shadcn/globals.css    shadcn/ui theme (Tailwind v4), from ../exports/shadcn/map.json
//   ../docs/shadcn.md                the shadcn mapping table
// The build fails on any broken rule, so a passing build is a passing check.
import fs from 'node:fs';
// Write a generated file only when its content changed, so an unchanged build leaves every file (and its date) alone.
const writeFile = fs.writeFileSync.bind(fs);
fs.writeFileSync = (file, data, ...rest) => { try { if (typeof data === 'string' && fs.readFileSync(file, 'utf8') === data) return; } catch {} return writeFile(file, data, ...rest); };
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatHex, clampChroma, rgb } from 'culori';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, 'tokens', f), 'utf8'));
const write = (f, s) => fs.writeFileSync(path.resolve(here, '..', f), s);
const fail = (m) => { console.error('✗ ' + m); process.exit(1); };
const r4 = (n) => Math.round(n * 1e4) / 1e4;
const cssVar = (name) => '--' + name.replaceAll('/', '-');
const fmt = ([l, c, h]) => `oklch(${l} ${c} ${h})`;
// In sRGB, allowing 8-bit rounding (±0.0005), so edge colours like #FF3D01 are not altered.
const inGamut = (l, c, h) => { const x = rgb({ mode: 'oklch', l, c, h }); return [x.r, x.g, x.b].every((v) => v > -5e-4 && v < 1 + 5e-4); };
const hexOf = ([l, c, h]) => formatHex({ mode: 'oklch', l, c, h }).toUpperCase();
const BANNER = (src) => `/* GENERATED by app/scripts/build-tokens.mjs from tokens/${src}. Do not edit. */`;

// ─── Colour: primitives from the recipe ───────────────────────────────────────
const colors = read('colors.json');
const { steps, ramps, white } = colors.primitive;
if (steps.lightness.length !== 12 || steps.chroma.length !== 12) fail('the scale must have exactly 12 steps');
for (let i = 1; i < 12; i++) if (steps.lightness[i] <= steps.lightness[i - 1]) fail(`lightness must rise step by step (step ${i + 1})`);

// Most chroma a hue can reach in sRGB at a given lightness
const maxChroma = (L, h) => { let lo = 0, hi = 0.4; for (let i = 0; i < 40; i++) { const m = (lo + hi) / 2; inGamut(L, m, h) ? (lo = m) : (hi = m); } return r4(lo); };
const prim = new Map();
for (const [ramp, spec] of Object.entries(ramps)) {
  if (!/^[a-z]+$/.test(ramp)) fail(`ramp "${ramp}" must be a lowercase hue name`);
  if (spec.chroma === 'max') spec.chroma = maxChroma(steps.lightness[8], spec.hue);
  steps.lightness.forEach((L, i) => {
    const want = spec.constant ? spec.chroma : spec.chroma * steps.chroma[i];
    // keep L and H; reduce C only if the colour does not fit sRGB
    const c = inGamut(L, want, spec.hue) ? want : clampChroma({ mode: 'oklch', l: L, c: want, h: spec.hue }, 'oklch', 'rgb').c;
    const lch = [r4(L), r4(c ?? 0), spec.hue];
    const name = `${ramp}/${i + 1}`;
    prim.set(name, { name, ramp, step: i + 1, lch, clamped: r4(want) > lch[1] });
  });
}
prim.set('white', { name: 'white', ramp: 'white', step: '', lch: white });
for (const p of prim.values()) Object.assign(p, { css: cssVar(p.name), hex: hexOf(p.lch) });
if (prim.get('orange/9').hex !== '#FF3D01') fail(`orange/9 must be the brand colour #FF3D01, got ${prim.get('orange/9').hex}`);

// ─── Colour: semantic roles ───────────────────────────────────────────────────
const semantic = [];
(function walk(node, trail) {
  for (const [k, v] of Object.entries(node)) {
    const name = [...trail, k].join('/');
    if (typeof v !== 'string') { walk(v, [...trail, k]); continue; }
    const ref = v.match(/^\{(.+)\}$/)?.[1];
    const p = prim.get(ref);
    if (!p) fail(`${name} → ${v} is not a primitive`);
    semantic.push({ name, group: trail[0] ?? name, ref, css: cssVar(name), lch: p.lch, hex: p.hex });
  }
})(colors.semantic, []);
const seen = new Set();
for (const s of semantic) { if (seen.has(s.css)) fail(`duplicate CSS variable ${s.css}`); seen.add(s.css); }

// ─── Motion ──────────────────────────────────────────────────────────────────
const motion = read('motion.json');
for (const [k, ms] of Object.entries(motion.duration)) if (!Number.isInteger(ms) || ms <= 0) fail(`duration/${k} must be a positive whole number of ms`);
const durs = Object.values(motion.duration);
for (let i = 1; i < durs.length; i++) if (durs[i] <= durs[i - 1]) fail('durations must grow fast → base → slow');
for (const [k, e] of Object.entries(motion.easing)) if (!/^cubic-bezier\(([^,]+,){3}[^,]+\)$/.test(e)) fail(`easing/${k} must be a cubic-bezier()`);

// ─── Light ───────────────────────────────────────────────────────────────────
const light = [];
for (const [name, e] of Object.entries(read('light.json'))) {
  if (name.startsWith('$')) continue;
  const ref = e.fill.match(/^\{(.+)\}$/)?.[1];
  const fill = semantic.find((s) => s.name === ref);
  if (!fill) fail(`light/${name} fill → ${e.fill} does not exist`);
  if (!(e.mediaOpacity < e.opacity)) fail(`light/${name} mediaOpacity must be lower than opacity`);
  const fadeKey = e.fade.match(/^\{duration\/(\w+)\}$/)?.[1];
  if (!motion.duration[fadeKey]) fail(`light/${name} fade → ${e.fade} is not a duration`);
  e.fadeRef = `duration/${fadeKey}`; e.fade = motion.duration[fadeKey];
  const BLENDS = ['normal', 'soft-light', 'overlay', 'screen'];
  if (!BLENDS.includes(e.blend)) fail(`light/${name} blend must be one of ${BLENDS.join(', ')}`);
  // The falloff of a disc (diameter size) under a Gaussian blur (sigma = Figma blur / 2), sampled into gradient stops.
  // This is what Figma draws, so a larger blur spreads the light wider and dimmer.
  const a = e.size / 2, sg = e.blur / 2, reach = Math.round(a + 3 * sg), N = 10, step = a / 60;
  const at = (d) => { let sum = 0; for (let x = -a; x <= a; x += step) for (let y = -a; y <= a; y += step) if (x * x + y * y <= a * a) sum += Math.exp(-((x - d) ** 2 + y * y) / (2 * sg * sg)); return sum * step * step / (2 * Math.PI * sg * sg); };
  const prof = Array.from({ length: N + 1 }, (_, i) => at((reach * i) / N)), peak = prof[0];
  const pc = (x) => `${+(x * 100).toFixed(2)}%`;
  const stops = (k, scale) => prof.map((v, i) => i === N ? `transparent ${reach}px` : `color-mix(in srgb, var(--light-${name}-${k}) ${pc(v * scale)}, transparent) ${Math.round((reach * i) / N)}px`).join(', ');
  light.push({ name: `light/${name}`, fill: ref, fillHex: fill.hex, blend: e.blend, opacity: e.opacity, mediaOpacity: e.mediaOpacity, size: e.size, blur: e.blur, fade: e.fade,
    peak, reach,
    vars: [[`--light-${name}-fill`, `var(${fill.css})`], [`--light-${name}-blend`, e.blend], [`--light-${name}-opacity`, String(e.opacity)],
           [`--light-${name}-media-opacity`, String(e.mediaOpacity)], [`--light-${name}-size`, `${e.size}px`],
           [`--light-${name}-blur`, `${e.blur / 2}px`], [`--light-${name}-fade`, `var(--duration-${fadeKey})`],
           [`--light-${name}-reach`, `${reach}px`], [`--light-${name}-stops`, stops('fill', 1)]], fadeRef: e.fadeRef });
}

// ─── Typography ──────────────────────────────────────────────────────────────
const type = read('typography.json');
const ROLES = ['display', 'heading', 'body', 'label'], SIZES = ['xs', 'sm', 'md', 'lg', 'xl'], EXTRA = ['2xl', '3xl'];
const WEIGHTS = Object.keys(type.weights);
if (WEIGHTS.join() !== 'regular,medium,semibold,bold') fail('weights must be regular, medium, semibold, bold');
const trackingFor = (size) => type.tracking.rules.find((r) => size <= r.maxSize).em;
const styles = [];
for (const role of ROLES) {
  if (!type.families[role]) fail(`missing family for ${role}`);
  let prev = 0;
  // every role has xs–xl; a role may add 2xl and 3xl, in order
  const own = Object.keys(type.sizes[role] || {});
  const extra = own.filter((k) => !SIZES.includes(k));
  if (extra.some((k, i) => k !== EXTRA[i])) fail(`${role}: extra sizes must be ${EXTRA.join(', ')} in order`);
  for (const size of [...SIZES, ...extra]) {
    const pair = type.sizes[role]?.[size];
    if (!pair) fail(`missing ${role}/${size}`);
    const [px, lh] = pair;
    if (px <= prev) fail(`${role}/${size} must be larger than the size before it`);
    if (EXTRA.includes(size) && lh % 4) fail(`${role}/${size} line height ${lh} must be on the 4px grid`);
    if (lh % 2) fail(`${role}/${size} line height ${lh} is off the 4px grid (2px half-step allowed)`);
    if (lh < px) fail(`${role}/${size} line height is smaller than the font size`);
    prev = px;
    styles.push({ role, size, px, lh, em: trackingFor(px), ratio: r4(lh / px) });
  }
}

// ─── Number ──────────────────────────────────────────────────────────────────
const num = read('number.json');
const space = num.space.values, stroke = num.stroke.values;
space.forEach((v, i) => {
  if (i && v <= space[i - 1]) fail('space values must grow');
  if (v > 8 ? v % 4 : v % 2) fail(`space/${v} is off the grid (4px; 2px half-steps up to 8)`);
});
const rOrder = Object.values(num.radius.values);
for (let i = 1; i < rOrder.length; i++) if (rOrder[i] <= rOrder[i - 1]) fail('radius values must grow none → full');
// Controls have seven sizes (2xs → 2xl); icons have five (xs → xl).
const CONTROL_SIZES = ['2xs', ...SIZES, '2xl'];
for (const [k, names] of [['control', CONTROL_SIZES], ['icon', SIZES]]) {
  const vals = names.map((sz) => num.size[k][sz]);
  if (vals.some((x) => !x) || Object.keys(num.size[k]).length !== names.length) fail(`size/${k} needs exactly ${names.join(', ')}`);
  vals.forEach((x, i) => { if (x % 4) fail(`size/${k}/${names[i]} must be on the 4px grid`); if (i && x <= vals[i - 1]) fail(`size/${k} must grow ${names[0]} → ${names.at(-1)}`); });
}
if (num.size.target < 44) fail('size/target must be at least 44px');
const grid = num.size.iconGrid;
if (!(grid.square < grid.circle && grid.circle <= 1 - 2 * grid.padding + 1e-3 && grid.stroke > 0)) fail('size/iconGrid: square < circle ≤ live area (1 − 2 × padding), stroke > 0');
const numbers = [
  ...space.map((v) => ({ name: `space/${v}`, px: v, group: 'space' })),
  ...Object.entries(num.radius.values).map(([k, v]) => ({ name: `radius/${k}`, px: v, group: 'radius' })),
  ...CONTROL_SIZES.map((k) => ({ name: `size/control/${k}`, px: num.size.control[k], group: 'size' })),
  ...SIZES.map((k) => ({ name: `size/icon/${k}`, px: num.size.icon[k], group: 'size' })),
  { name: 'size/target', px: num.size.target, group: 'size' },
  ...['padding', 'square', 'circle', 'stroke'].map((k) => ({ name: `size/icon/grid/${k}`, px: grid[k], ratio: true, group: 'size' })),
  ...stroke.map((v) => ({ name: `stroke/${v}`, px: v, group: 'stroke' })),
].map((n) => ({ ...n, css: cssVar(n.name) }));

// ─── Components ──────────────────────────────────────────────────────────────
// A spec references tokens as {group/name}. Every reference must exist; the build resolves them.
const tokenExists = (ref) => semantic.some((x) => x.name === ref) || numbers.some((x) => x.name === ref)
  || /^type\/(display|heading|body|label)\/(xs|sm|md|lg|xl|2xl|3xl)\/(regular|medium|semibold|bold)$/.test(ref) && styles.some((s) => `type/${s.role}/${s.size}` === ref.split('/').slice(0, 3).join('/'));
const refOf = (v, where) => { const r = String(v).match(/^\{(.+)\}$/)?.[1]; if (!r || !tokenExists(r)) fail(`${where}: ${v} is not a token`); return r; };
const components = {};
const compDir = path.join(root, 'components');
for (const file of fs.existsSync(compDir) ? fs.readdirSync(compDir).filter((f) => f.endsWith('.json')) : []) {
  const name = file.replace('.json', ''), spec = JSON.parse(fs.readFileSync(path.join(compDir, file), 'utf8'));
  if (name === 'button') {
    const sizes = Object.entries(spec.sizes).map(([size, sz]) => {
      const height = numbers.find((n) => n.name === `size/control/${size}`);
      if (!height) fail(`button/${size}: size/control/${size} does not exist`);
      // a plain number is a set value that is not a token (e.g. 2xs padding x 10)
      const px = typeof sz.paddingX === 'number' ? null : refOf(sz.paddingX, `button/${size} paddingX`), gap = refOf(sz.gap, `button/${size} gap`), label = refOf(sz.label, `button/${size} label`);
      const pxVal = px ? numbers.find((n) => n.name === px).px : sz.paddingX;
      const [, role, tsize] = label.split('/'), st = styles.find((x) => x.role === role && x.size === tsize);
      const iconRef = refOf(sz.icon, `button/${size} icon`), icon = numbers.find((n) => n.name === iconRef).px;
      const radius = typeof sz.radius === 'number' ? sz.radius : Math.round((height.px * spec.squircle) / 4) * 4;
      for (const [k, val] of [['height', height.px], ['padding x', pxVal], ['gap', numbers.find((n) => n.name === gap).px], ['icon', icon], ['radius', radius]]) if (val >= 12 ? val % 4 : val % 2) fail(`button/${size} ${k} ${val} is off the grid (4px; 2px half-steps under 12)`);
      return { size, height: height.px, heightToken: height.name, paddingX: pxVal, paddingXToken: px, radiusSet: typeof sz.radius === 'number',
        gap: numbers.find((n) => n.name === gap).px, gapToken: gap, label, labelClass: 'type-' + label.slice(5).replaceAll('/', '-'),
        font: st.px, lineHeight: st.lh, icon, iconToken: iconRef, paddingY: (height.px - Math.max(icon, st.lh)) / 2, radius };
    });
    sizes.forEach((x, i) => { if (i && x.height <= sizes[i - 1].height) fail('button sizes must grow'); });
    const STATES = ['rest', 'hover', 'pressed', 'disabled'];
    const refOrNone = (v, where) => (v === 'none' ? 'none' : refOf(v, where));
    const types = Object.fromEntries(Object.entries(spec.types).map(([type, t]) => {
      for (const st of STATES) if (!t[st]) fail(`button/${type} is missing the ${st} state`);
      // shade follows the fill: a state with a fill gets the inner shade, a state without one doesn't
      return [type, { about: t.$about, ...Object.fromEntries(STATES.map((st) =>
        [st, { ...Object.fromEntries(Object.entries(t[st]).map(([part, v]) => [part, refOrNone(v, `button/${type}/${st} ${part}`)])), shade: t[st].fill !== 'none' }])) }];
    }));
    const links = Object.fromEntries(Object.entries(spec.links).map(([k, l]) =>
      [k, { about: l.$about, ...Object.fromEntries(STATES.map((st) => [st, refOf(l[st], `button/link-${k}/${st}`)])) }]));
    components.button = { ...spec, sizes, types, links };
  }
  if (name !== 'button') {
    // Every other component is a parts spec (D-025): title, status, css { selector, prefix }, anatomy, rules, parts.
    // Every leaf of parts is a token reference, a plain number (a set px value) or none. A "type" leaf must be a
    // type style; it becomes a class name. Each leaf becomes --{prefix}-{path} on the component's selector.
    for (const k of ['title', 'status', 'anatomy', 'rules', 'parts']) if (!spec[k]) fail(`${name}: ${k} is missing`);
    if (!['draft', 'stable', 'deprecated'].includes(spec.status)) fail(`${name}: status must be draft, stable or deprecated`);
    if (!/^\.[a-z][a-z0-9-]*$/.test(spec.css?.selector || '') || !/^[a-z][a-z0-9]*$/.test(spec.css?.prefix || '')) fail(`${name}: css needs a selector (.class) and a prefix (lowercase letters and digits)`);
    const owner = Object.entries(components).find(([, x]) => x.css?.prefix === spec.css.prefix);
    if (owner) fail(`${name}: css prefix "${spec.css.prefix}" is already used by ${owner[0]}`);
    const vars = [], types = {};
    const walk = (o, trail) => {
      for (const [k, v] of Object.entries(o)) {
        if (k.startsWith('$')) continue;
        const key = [...trail, k].join('-'), where = `${name}/${[...trail, k].join('/')}`;
        if (v && typeof v === 'object') walk(v, [...trail, k]);
        else if (k === 'type') { const r = refOf(v, where); if (!r.startsWith('type/')) fail(`${where}: ${v} is not a type style`); types[trail.join('-')] = 'type-' + r.slice(5).replaceAll('/', '-'); }
        else if (typeof v === 'number') { if (v % 2) fail(`${where} ${v} is off the 2px half-step grid`); vars.push({ key, px: v }); }
        else if (v === 'none') vars.push({ key, none: true });
        else vars.push({ key, ref: refOf(v, where) });
      }
    };
    walk(spec.parts, []);
    components[name] = { ...spec, vars, types };
  }
}

// ─── Write CSS ───────────────────────────────────────────────────────────────
const css = [BANNER('*.json'), ':root {', '  color-scheme: dark;', ''];
for (const ramp of Object.keys(ramps)) {
  css.push(`  /* Colour · ${ramp} */`);
  for (let i = 1; i <= 12; i++) { const p = prim.get(`${ramp}/${i}`); css.push(`  ${p.css}: ${fmt(p.lch)};`); }
}
css.push(`  --white: ${fmt(white)};`, '');
let g = null;
for (const s of semantic) {
  if (s.group !== g) { g = s.group; css.push(`  /* Semantic · ${g} */`); }
  css.push(`  ${s.css}: var(${cssVar(s.ref)});`);
}
css.push('', '  /* Light */');
for (const l of light) for (const [k, val] of l.vars) css.push(`  ${k}: ${val};`);
css.push('', '  /* Type · families and weights */');
for (const role of ROLES) css.push(`  --font-${role}: ${type.families[role].css}, ${type.families[role].fallback};`);
for (const w of WEIGHTS) css.push(`  --font-weight-${w}: ${type.weights[w]};`);
css.push('  /* Type · sizes */');
for (const s of styles) {
  const k = `--type-${s.role}-${s.size}`;
  css.push(`  ${k}-size: ${s.px}px;`, `  ${k}-line-height: ${s.lh}px;`, `  ${k}-tracking: ${s.em}em;`);
}
css.push('', '  /* Number */');
for (const n of numbers) css.push(`  ${n.css}: ${n.ratio ? n.px : `${n.px}px`};`);
css.push('', '  /* Motion */');
for (const [k, ms] of Object.entries(motion.duration)) css.push(`  --duration-${k}: ${ms}ms;`);
for (const [k, e] of Object.entries(motion.easing)) css.push(`  --easing-${k}: ${e};`);
css.push('}', '');
write('src/styles/tokens.css', css.join('\n'));

const tcss = [BANNER('typography.json'), '/* One class per style: .type-{role}-{size}-{weight}. */'];
for (const s of styles) for (const w of WEIGHTS) {
  const k = `--type-${s.role}-${s.size}`;
  tcss.push(`.type-${s.role}-${s.size}-${w} { font-family: var(--font-${s.role}); font-size: var(${k}-size); line-height: var(${k}-line-height); letter-spacing: var(${k}-tracking); font-weight: var(--font-weight-${w}); }`);
}
write('src/styles/typography.css', tcss.join('\n') + '\n');

